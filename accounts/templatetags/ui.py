    return format_html(
        '<svg viewBox="0 0 24 24" fill="{}" stroke="currentColor" stroke-width="1.8" '
        'stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">{}</svg>',
        fill, mark_safe(_PATHS[name]),
    )


